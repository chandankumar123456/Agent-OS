"""Benchmark: find docs -> summarize -> generate webpage -> preview

Validates Sprint 2 end-to-end by exercising document, code, filesystem,
and browser MCP servers in sequence.
"""
import asyncio
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.mcp.client_manager import MCPClientManager
from app.tools.registry import tool_registry


async def benchmark():
    print("=" * 60)
    print("SPRINT 2 BENCHMARK: find docs -> summarize -> generate webpage -> preview")
    print("=" * 60)

    # ── 1. Start MCP system servers ────────────────────────────────────
    print("\n[1/5] Starting MCP system servers...")
    manager = MCPClientManager()
    await manager.start_system_servers()
    # Register discovered MCP tools in ToolRegistry v1 so execute() works
    await tool_registry.discover_mcp_tools()
    mcp_tools = await manager.list_tools()
    print(f"      MCP servers ready. {len(mcp_tools)} tools discovered.")

    required = {
        "document__parse", "document__chunk", "document__summarize",
        "code_executor__run_python",
        "filesystem__write_file", "filesystem__read_file",
        "browser_env__launch", "browser_env__navigate",
    }
    missing = required - {t["name"] for t in mcp_tools}
    if missing:
        print(f"      WARNING: Missing MCP tools: {missing}")
    else:
        print("      All required tools present.")

    # ── 2. Create sample document and parse/summarize ──────────────────
    print("\n[2/5] Creating sample document and summarizing...")
    with tempfile.NamedTemporaryFile(mode="w", suffix=".txt", delete=False) as f:
        f.write(
            "AgentOS Architecture Audit\n"
            "==========================\n\n"
            "AgentOS is a FastAPI-based agent execution platform.\n"
            "It uses LangGraph as the primary execution engine with PostgreSQL checkpointing.\n"
            "MCP servers provide filesystem, shell, cloud API, desktop, browser, document, and code capabilities.\n"
            "The platform supports per-task session isolation for browser and desktop automation.\n"
            "Key components include ToolRegistry v1, ToolGroundingLayer, SafetyGate, and DeterministicVerificationEngine.\n"
        )
        doc_path = f.name

    try:
        # Parse + summarize via document MCP server
        parse_result = await tool_registry.execute("document__parse", {"path": doc_path, "skip_summary": False})
        assert parse_result.success, f"Parse failed: {parse_result.error}"
        doc_data = parse_result.result["output"]
        doc_json = json.loads(doc_data)
        assert doc_json["success"], f"Document parse returned error: {doc_json.get('error')}"
        summary = doc_json["result"].get("summary", "")
        text = doc_json["result"].get("text", "")
        print(f"      Document parsed: {len(text)} chars")
        print(f"      Summary preview: {summary[:120]}...")

        # Chunk the text
        chunk_result = await tool_registry.execute("document__chunk", {"text": text, "chunk_size": 200, "overlap": 20})
        assert chunk_result.success, f"Chunk failed: {chunk_result.error}"
        chunk_json = json.loads(chunk_result.result["output"])
        assert chunk_json["success"], f"Chunk returned error: {chunk_json.get('error')}"
        chunks = chunk_json["result"]["chunks"]
        print(f"      Chunks created: {len(chunks)}")
    finally:
        os.unlink(doc_path)

    # ── 3. Generate webpage via code execution ─────────────────────────
    print("\n[3/5] Generating summary webpage via code execution...")
    html_content = f"""<!DOCTYPE html>
<html>
<head><title>AgentOS Summary</title></head>
<body>
<h1>AgentOS Architecture Summary</h1>
<p><strong>Generated by:</strong> Sprint 2 Benchmark</p>
<hr/>
<h2>Summary</h2>
<p>{summary[:500]}</p>
<h2>Key Facts</h2>
<ul>
<li>Platform: FastAPI + LangGraph</li>
<li>Database: PostgreSQL with checkpointing</li>
<li>MCP Servers: filesystem, shell, cloud_api, desktop, browser, document, code</li>
<li>Session Isolation: per-task browser/desktop contexts</li>
</ul>
<h2>Chunks</h2>
<p>Document split into {len(chunks)} semantic chunks.</p>
</body>
</html>"""

    with tempfile.TemporaryDirectory() as tmpdir:
        html_path = os.path.join(tmpdir, "summary.html")

        # Write file via filesystem MCP
        write_result = await tool_registry.execute("filesystem__write_file", {"path": html_path, "content": html_content})
        assert write_result.success, f"Write failed: {write_result.error}"
        print(f"      Webpage written: {html_path}")

        # Verify via filesystem read
        read_result = await tool_registry.execute("filesystem__read_file", {"path": html_path})
        assert read_result.success, f"Read failed: {read_result.error}"
        assert "AgentOS Architecture Summary" in read_result.result["output"]
        print(f"      Webpage verified: {len(read_result.result['output'])} bytes")

        # ── 4. Preview in browser ──────────────────────────────────────
        print("\n[4/5] Previewing webpage in browser...")
        launch_result = await tool_registry.execute("browser_env__launch", {"task_id": "benchmark", "headless": True})
        assert launch_result.success, f"Browser launch failed: {launch_result.error}"
        print(f"      Browser launched (headless)")

        file_url = f"file:///{html_path.replace(chr(92), '/')}"
        nav_result = await tool_registry.execute("browser_env__navigate", {"task_id": "benchmark", "url": file_url})
        assert nav_result.success, f"Browser navigate failed: {nav_result.error}"
        print(f"      Navigated to {file_url}")

        screenshot_result = await tool_registry.execute("browser_env__screenshot", {"task_id": "benchmark", "path": os.path.join(tmpdir, "screenshot.png")})
        assert screenshot_result.success, f"Screenshot failed: {screenshot_result.error}"
        ss_json = json.loads(screenshot_result.result["output"])
        assert ss_json.get("success"), f"Screenshot returned error: {ss_json.get('error')}"
        print(f"      Screenshot saved: {os.path.join(tmpdir, 'screenshot.png')}")

        close_result = await tool_registry.execute("browser_env__close", {"task_id": "benchmark"})
        assert close_result.success, f"Browser close failed: {close_result.error}"
        print(f"      Browser closed")

    # ── 5. Cleanup ─────────────────────────────────────────────────────
    print("\n[5/5] Disconnecting MCP servers...")
    await manager.disconnect_all()
    print("      Done.")

    print("\n" + "=" * 60)
    print("BENCHMARK PASSED")
    print("=" * 60)


if __name__ == "__main__":
    asyncio.run(benchmark())
